CONNECT TO YYDEMO;
EXPLAIN PLAN SET QUERYNO=777017 FOR
SELECT customer_id, COUNT(*) FROM orders GROUP BY customer_id;
EXPORT TO db2-plan.db2plan OF DEL MODIFIED BY CODEPAGE=1208
WITH stmt AS (
  SELECT * FROM EXPLAIN_STATEMENT
  WHERE QUERYNO=777017 AND EXPLAIN_REQUESTER=CURRENT USER AND EXPLAIN_LEVEL='P'
  ORDER BY EXPLAIN_TIME DESC FETCH FIRST 1 ROW ONLY
), ops AS (
  SELECT o.* FROM EXPLAIN_OPERATOR o JOIN stmt t ON
    o.EXPLAIN_REQUESTER=t.EXPLAIN_REQUESTER AND o.EXPLAIN_TIME=t.EXPLAIN_TIME
    AND o.SOURCE_NAME=t.SOURCE_NAME AND o.SOURCE_SCHEMA=t.SOURCE_SCHEMA
    AND o.SOURCE_VERSION=t.SOURCE_VERSION AND o.EXPLAIN_LEVEL=t.EXPLAIN_LEVEL
    AND o.STMTNO=t.STMTNO AND o.SECTNO=t.SECTNO
), streams AS (
  SELECT s.* FROM EXPLAIN_STREAM s JOIN stmt t ON
    s.EXPLAIN_REQUESTER=t.EXPLAIN_REQUESTER AND s.EXPLAIN_TIME=t.EXPLAIN_TIME
    AND s.SOURCE_NAME=t.SOURCE_NAME AND s.SOURCE_SCHEMA=t.SOURCE_SCHEMA
    AND s.SOURCE_VERSION=t.SOURCE_VERSION AND s.EXPLAIN_LEVEL=t.EXPLAIN_LEVEL
    AND s.STMTNO=t.STMTNO AND s.SECTNO=t.SECTNO
)
SELECT o.OPERATOR_ID,
  (SELECT MIN(s.TARGET_ID) FROM streams s
   WHERE s.SOURCE_TYPE='O' AND s.TARGET_TYPE='O' AND s.SOURCE_ID=o.OPERATOR_ID),
  o.OPERATOR_TYPE,
  (SELECT MIN(s.OBJECT_SCHEMA || '.' || s.OBJECT_NAME) FROM streams s
   WHERE s.TARGET_ID=o.OPERATOR_ID AND s.SOURCE_TYPE='D'),
  (SELECT MAX(s.STREAM_COUNT) FROM streams s
   WHERE s.SOURCE_ID=o.OPERATOR_ID AND s.SOURCE_TYPE='O'),
  o.TOTAL_COST,o.IO_COST,o.CPU_COST
FROM ops o ORDER BY o.OPERATOR_ID;
CONNECT RESET;
